     * (Cairo/Giza cheapest, Alexandria next, Delta/Canal mid, Upper Egypt
     * higher, remote/border governorates most expensive).
     *
     * @return array<int, array{name_ar: string, name_en: string, fee: float}>
     */
    public static function cities(): array
    {
        $tier = fn (array $names, float $fee) => array_map(fn ($pair) => [
            'name_ar' => $pair[0], 'name_en' => $pair[1], 'fee' => $fee,
        ], $names);

        return array_merge(
            $tier([['القاهرة', 'Cairo'], ['الجيزة', 'Giza']], 60),
            $tier([['الإسكندرية', 'Alexandria']], 70),
            $tier([
                ['الدقهلية', 'Dakahlia'], ['البحيرة', 'Beheira'], ['الغربية', 'Gharbia'],
